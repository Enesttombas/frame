const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const core = require('./core.js');
const cues = core.parseSubtitles('1\n00:00:00,000 --> 00:00:02,500\nFirst <b>line</b>.\n\n2\n00:00:03,000 --> 00:00:05,000\nSecond line.');
assert.equal(cues.length, 2); assert.equal(cues[0].en, 'First line.');
assert.equal(core.activeCue(cues, 0), 0); assert.equal(core.activeCue(cues, 2.5), -1); assert.equal(core.activeCue(cues, 3), 1); assert.equal(core.activeCue(cues, 5), -1);
assert.equal(core.parseSubtitles('WEBVTT\n\n00:01.200 --> 00:02.900 align:start\nHello')[0].start, 1.2);
assert.throws(() => core.parseSubtitles('no timestamps'));
assert.throws(() => core.parseSubtitles('1\n00:00:08,000 --> 00:00:01,000\nWrong'));
const cards = []; assert.equal(core.addCard(cards, 'line', cues[0], 'lesson'), true); assert.equal(core.addCard(cards, 'LINE', cues[0], 'lesson'), false); assert.equal(cards.length, 1);
assert.equal(core.activeCue([{ start: 0, end: 10 }, { start: 2, end: 3 }], 4), 0);
const context = { window: {} }; vm.createContext(context);
vm.runInContext(fs.readFileSync('lesson.js', 'utf8'), context); vm.runInContext(fs.readFileSync('timings.js', 'utf8'), context);
const lesson = context.window.FRAME_LESSON, timings = context.window.FRAME_TIMINGS;
assert.equal(lesson.cues.length, timings.length); assert.equal(lesson.cues.length, 8);
lesson.cues.forEach((cue, i) => { assert.ok(cue.en.includes(cue.focus)); assert.ok(lesson.dictionary[cue.focus]); assert.ok(timings[i].end > timings[i].start); if (i) assert.ok(timings[i].start >= timings[i - 1].end - .002); });
assert.ok(fs.statSync('media/lesson.mp4').size > 10000);
for (const file of ['app.js', 'core.js', 'lesson.js', 'timings.js']) new vm.Script(fs.readFileSync(file, 'utf8'), { filename: file });
console.log('PASS: SRT/VTT, cue boundaries, overlaps, duplicate cards, 8 lesson timings, media and JS syntax.');
